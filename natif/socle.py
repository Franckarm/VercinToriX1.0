        a.alu("cmp", AL, 32)
        a.jcc("be", "PAR_B")
        a.pop(RSI)
        a.jmp("OS_PARLER")
        a.etiquette("PAR_RIEN")
        a.pop(RSI)
        a.ret()

        # FINI : ecx le canal -> eax 1 si rien de plus à lire
        a.etiquette("FINI")
        a.call("CANAL")
        a.jcc("e", "FINI_1")
        a.alu("cmp", qword(RDX, depl=K_MODE), 1)
        a.jcc("ne", "FINI_1")
        a.mov(RAX, qword(RDX, depl=K_POS))
        a.alu("cmp", RAX, qword(RDX, depl=K_LONG))
        a.jcc("ae", "FINI_1")
        a.alu("xor", EAX, EAX)
        a.ret()
        a.etiquette("FINI_1")
        a.mov(EAX, 1)
        a.ret()

        # BLOC : eax 6 (écrire) ou 7 (lire) : nom, adresse globale et nombre de mots en @3[14680060..14680062]
        a.etiquette("BLOC")
        self.sauver(TOUS)
        a.alu("cmp", qword(RBP, depl=CORPUS), 0)
        a.jcc("ne", "OUV_ECHEC")
        a.mov(EBX, EAX)
        base = (3 << 26) + 14680060 * 4
        a.mov(EAX, dword(R15_, depl=base))
        a.call("CHEMIN_DE")
        a.mov(R32[12], dword(R15_, depl=base + 4))    # adresse globale
        a.mov(R32[13], dword(R15_, depl=base + 8))    # nombre de mots
        a.mov(R32[14], R32[12])
        a.alu("and", R32[14], ADR)                     # o
        a.decaler("shr", R32[12], 24)
        a.alu("and", R32[12], 3)
        a.decaler("shl", R32[12], 24)                  # e << 24
        a.lea(RDI, qword(RBP, depl=CHEMIN))
        a.alu("cmp", EBX, 6)
        a.jcc("ne", "BLOC_LIRE")
        # écrire : les mots dans une région, puis le fichier
        a.mov(RSI, R64[13])
