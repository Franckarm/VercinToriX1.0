"""Le socle d'exécution des programmes traduits en x86-64 : démarrage, entrées, sorties, texte, canaux (console,
fichiers, voix), services (bruit, cubes, blocs de mémoire), fin et erreurs.

Le socle est un bloc de code fixe, indépendant de sa position, placé en tête de chaque exécutable ; il ne dépend du
programme que par son descripteur (64 premiers octets : adresses de la zone d'état, de la table des retours, des mots du
programme, de la première instruction ; nombre de mots ; mode corpus). Le traducteur écrit en vtx n'aura donc qu'à
recopier ces octets et remplir le descripteur.

Seules les primitives OS_* parlent au système (Linux : appels système) ; le reste est commun.

Conventions : les routines préservent tous les registres sauf rax, rcx, rdx (et les drapeaux), sauf mention contraire.
rbp : la zone d'état ; r15 : la mémoire du SPU (4 étages de 16 M mots, 64 Mo chacun).
"""
from x86 import *  # noqa

ADR = 0xFFFFFF
MASQUE = 0xFFFFFFFF
PILE_HAUT = 0x7FFFFF
ETAGE_OCTETS = 1 << 26

# registres du SPU tenus dans des registres de la machine (les autres : [rbp + 4r])
CARTE = {1: 3, 2: 6, 3: 7, 4: 8, 9: 9, 10: 10, 11: 11, 12: 12, 13: 13, 14: 14}

# --- la zone d'état ([rbp + ...])
Z, C = 64, 68
NS, NT, IPOS, INB, SBASE, TBASE, IBASE, OUTPOS = 72, 80, 88, 96, 104, 112, 120, 128
F2_31, FREQ = 136, 144                     # FREQ : 4 mots (fréquence de chaque étage)
PREMIER, OCTET, CORPUS, FD, NCUBES, ENVP = 168, 176, 184, 192, 200, 208
OUTBUF, TOUT = 4096, 65536
VEC = OUTBUF + TOUT                        # vecteur de mincore (une case par page des étages 1 à 3)
CHIFFRES = VEC + 49152                     # 4096 octets de travail (chiffres, un caractère, ...)
CHEMIN = CHIFFRES + 4096                   # un nom de fichier en UTF-8 (4096 caractères au plus, 4 octets chacun)
TCHEMIN = 16448
CANAUX = CHEMIN + TCHEMIN                  # 1024 canaux de 64 octets
NCANAUX = 1024
CUBES = CANAUX + 64 * NCANAUX              # 256 cubes rangés : étage, fréquence, adresse
NCUBES_MAX = 256
TAILLE_ETAT = CUBES + 16 * NCUBES_MAX
# un canal : mode (0 libre, 1 lecture, 2 écriture), tampon (mots), longueur, position, nom, région, taille de la région
K_MODE, K_TAMPON, K_LONG, K_POS, K_NOM, K_REGION, K_TAILLE = 0, 8, 16, 24, 32, 40, 48

GO = 1 << 30
SORTIES_MAX, TEXTE_MAX, ENTREES_MAX = GO, GO, 1 << 26
ECRITURE_MAX = 1 << 31                     # tampon d'un fichier ouvert en écriture (réservé, rempli à la demande)

# descripteur (en tête du socle)
D_ETAT, D_TABLE, D_PROGRAMME, D_N, D_P0, D_CORPUS = 0, 8, 16, 24, 32, 40
TAILLE_DESCRIPTEUR = 64

TOUS = [RCX, RDX, RBX, RSI, RDI, R8_, R9_, R10_, R11_, R12_, R13_, R14_]

# les entrées du socle appelées par le code traduit
ENTREES_SOCLE = ["ENTREE", "SORTIE", "ENTC", "SORC", "SYS", "GDOT", "GEMV", "QUITS", "FIN", "E_RETOUR", "E_HORS",
                 "E_DMA", "E_INCONNU"]


class Socle:
    def __init__(self, a, systeme="linux"):
        self.a = a
        self.systeme = systeme
        self.messages = []

    def msg(self, texte):
        """Charge rsi, ecx avec un message (rangé à la fin du socle)."""
        nom = f"MSG{len(self.messages)}"
        self.messages.append((nom, texte))
        self.a.lea(RSI, qword(etiq=nom))
        self.a.mov(ECX, len(texte.encode()))

    def sauver(self, regs):
        for r in regs:
            self.a.push(r)

    def restaurer(self, regs):
        for r in reversed(regs):
            self.a.pop(r)

    # ================= primitives du système (Linux)
    def primitives(self):
        if self.systeme == "windows":
            from socle_windows import primitives_windows
            return primitives_windows(self)
        a = self.a

        # OS_INIT : rien à préparer sous Linux
        a.etiquette("OS_INIT")
        a.ret()

        # OS_PAGES : VEC[i] = 1 si la page i des étages 1 à 3 est présente (mincore)
        a.etiquette("OS_PAGES")
        self.sauver([RCX, RDX, RSI, RDI, R11_])
        a.lea(RDI, qword(R15_, depl=1 << 26))
        a.mov(ESI, 3 << 26)
        a.lea(RDX, qword(RBP, depl=VEC))
        a.mov(EAX, 27)
        a.syscall()
        self.restaurer([RCX, RDX, RSI, RDI, R11_])
        a.ret()

        def appel(n):
            a.mov(EAX, n)
            a.syscall()

        # OS_ECRIRE : edi le descripteur, rsi le tampon, rdx la longueur (tout est écrit) ; rax < 0 en cas d'échec
        a.etiquette("OS_ECRIRE")
        self.sauver([RCX, RDX, RSI, R11_])
        a.etiquette("OS_ECRIRE_B")
        a.test(RDX, RDX)
        a.jcc("e", "OS_ECRIRE_F")
        appel(1)
        a.test(RAX, RAX)
        a.jcc("le", "OS_ECRIRE_X")
        a.alu("add", RSI, RAX)
        a.alu("sub", RDX, RAX)
        a.jmp("OS_ECRIRE_B")
        a.etiquette("OS_ECRIRE_F")
        a.alu("xor", EAX, EAX)
        a.etiquette("OS_ECRIRE_X")
        self.restaurer([RCX, RDX, RSI, R11_])
        a.ret()

        # OS_LIRE : edi, rsi, rdx -> rax octets lus (0 à la fin, < 0 en cas d'échec)
        a.etiquette("OS_LIRE")
        self.sauver([RCX, R11_])
        appel(0)
        self.restaurer([RCX, R11_])
        a.ret()

        # OS_OUVRIR : rdi le nom (terminé par 0), esi 0 lecture / 1 écriture (créé, vidé) -> rax descripteur (< 0 : échec)
        a.etiquette("OS_OUVRIR")
        self.sauver([RCX, RDX, RSI, R11_])
        a.test(ESI, ESI)
        a.mov(EDX, 0o644)
        a.mov(ESI, 0)
        a.jcc("e", "OS_OUVRIR_L")
        a.mov(ESI, 0x241)                  # O_WRONLY | O_CREAT | O_TRUNC
        a.etiquette("OS_OUVRIR_L")
        appel(2)
        self.restaurer([RCX, RDX, RSI, R11_])
        a.ret()

        # OS_FERMER : edi
        a.etiquette("OS_FERMER")
        self.sauver([RCX, R11_])
        appel(3)
        self.restaurer([RCX, R11_])
        a.ret()

        # OS_TAILLE : edi -> rax la taille du fichier (lseek à la fin puis au début)
        a.etiquette("OS_TAILLE")
        self.sauver([RCX, RDX, RSI, R11_])
        a.alu("xor", ESI, ESI)
        a.mov(EDX, 2)
        appel(8)
        a.push(RAX)
        a.alu("xor", ESI, ESI)
        a.alu("xor", EDX, EDX)
        appel(8)
        a.pop(RAX)
        self.restaurer([RCX, RDX, RSI, R11_])
        a.ret()

        # OS_RESERVER : rsi la taille -> rax l'adresse (mémoire à zéro, remplie à la demande), < 0 : échec
        a.etiquette("OS_RESERVER")
        self.sauver([RCX, RDX, RDI, R8_, R9_, R10_, R11_])
        a.alu("xor", EDI, EDI)
        a.mov(EDX, 3)
        a.mov(R32[10], 0x4022)             # MAP_PRIVATE | MAP_ANONYMOUS | MAP_NORESERVE
        a.mov(R64[8], -1)
        a.alu("xor", R32[9], R32[9])
        appel(9)
        self.restaurer([RCX, RDX, RDI, R8_, R9_, R10_, R11_])
        a.ret()

        # OS_RENDRE : rdi l'adresse, rsi la taille
        a.etiquette("OS_RENDRE")
        self.sauver([RCX, R11_])
        appel(11)
        self.restaurer([RCX, R11_])
        a.ret()

        # OS_QUITTER : edi le code de sortie
        a.etiquette("OS_QUITTER")
        appel(60)

        # OS_BRUIT -> eax : 32 bits du hasard du système
        a.etiquette("OS_BRUIT")
        self.sauver([RCX, RDX, RSI, RDI, R11_])
        a.lea(RDI, qword(RBP, depl=OCTET))
        a.mov(ESI, 4)
        a.alu("xor", EDX, EDX)
        appel(318)                          # getrandom
        a.mov(EAX, dword(RBP, depl=OCTET))
        self.restaurer([RCX, RDX, RSI, RDI, R11_])
        a.ret()

        # OS_PARLER : rsi le texte en UTF-8 terminé par 0 : espeak-ng (ou espeak), comme la machine Rust
        a.etiquette("OS_PARLER")
        self.sauver(TOUS)
        a.mov(RBX, RSI)
        appel(57)                           # fork
        a.test(RAX, RAX)
        a.jcc("s", "OS_PARLER_F")
        a.jcc("ne", "OS_PARLER_P")
        # l'enfant : sorties vers /dev/null, puis execve
        a.lea(RDI, qword(etiq="NUL_CHEMIN"))
        a.mov(ESI, 2)
        a.alu("xor", EDX, EDX)
        appel(2)
        a.mov(R64[12], RAX)
        for fd in (1, 2):
            a.mov(RDI, R64[12])
            a.mov(ESI, fd)
            appel(33)                       # dup2
        a.lea(RSI, qword(RBP, depl=CHIFFRES))      # argv : prog, -v, fr, texte, 0
        for i, et in enumerate(("ESPEAK_NG", "OPT_V", "OPT_FR")):
            a.lea(RAX, qword(etiq=et))
            a.mov(qword(RSI, depl=8 * i), RAX)
        a.mov(qword(RSI, depl=24), RBX)
        a.mov(qword(RSI, depl=32), 0)
        a.mov(RDX, qword(RBP, depl=ENVP))
        a.lea(RDI, qword(etiq="CHEMIN_ESPEAK_NG"))
        a.mov(qword(RSI), RDI)
        appel(59)
        a.lea(RDI, qword(etiq="CHEMIN_ESPEAK"))
        a.mov(qword(RSI), RDI)
        appel(59)
        a.mov(EDI, 127)
        appel(60)
        a.etiquette("OS_PARLER_P")
        a.mov(RDI, RAX)
        a.alu("xor", ESI, ESI)
        a.alu("xor", EDX, EDX)
        a.alu("xor", R32[10], R32[10])
        appel(61)                           # wait4
        a.etiquette("OS_PARLER_F")
        self.restaurer(TOUS)
        a.ret()

        # OS_ACCORDER : ecx l'étage (1 à 3), edx la nouvelle fréquence, eax l'ancienne : range le cube de l'étage
        # (déplacé, sans copie : mremap) et ramène celui de la fréquence demandée (ou un étage vide)
        a.etiquette("OS_ACCORDER")
        self.sauver(TOUS)
        a.mov(EBX, ECX)                     # étage
        a.mov(R32[12], EAX)                 # ancienne fréquence
        a.mov(R32[13], EDX)                 # nouvelle
        a.mov(R64[14], RBX)
        a.decaler("shl", R64[14], 26)
        a.alu("add", R64[14], R15_)         # adresse de l'étage
        a.mov(RAX, qword(RBP, depl=NCUBES))
        a.alu("cmp", RAX, NCUBES_MAX)
        a.jcc("ae", "E_CUBES")
        # une place réservée (sans accès) pour y ranger l'étage
        a.alu("xor", EDI, EDI)
        a.mov(ESI, ETAGE_OCTETS)
        a.alu("xor", EDX, EDX)
        a.mov(R32[10], 0x4022)
        a.mov(R64[8], -1)
        a.alu("xor", R32[9], R32[9])
        appel(9)
        a.test(RAX, RAX)
        a.jcc("s", "E_CUBES")
        a.mov(R64[8], RAX)
        a.mov(RDI, R64[14])
        a.mov(ESI, ETAGE_OCTETS)
        a.mov(EDX, ETAGE_OCTETS)
        a.mov(R32[10], 3)                   # MREMAP_MAYMOVE | MREMAP_FIXED
        appel(25)
        a.test(RAX, RAX)
        a.jcc("s", "E_CUBES")
        # noter (étage, ancienne fréquence, adresse)
        a.mov(RCX, qword(RBP, depl=NCUBES))
        a.decaler("shl", RCX, 4)
        a.mov(dword(RBP, RCX, 1, CUBES), EBX)
        a.mov(dword(RBP, RCX, 1, CUBES + 4), R32[12])
        a.mov(qword(RBP, RCX, 1, CUBES + 8), RAX)
        a.alu("add", qword(RBP, depl=NCUBES), 1)
        # le cube demandé est-il rangé ?
        a.alu("xor", ECX, ECX)
        a.etiquette("OS_ACC_CH")
        a.alu("cmp", RCX, qword(RBP, depl=NCUBES))
        a.jcc("ae", "OS_ACC_NEUF")
        a.mov(RDX, RCX)
        a.decaler("shl", RDX, 4)
        a.alu("cmp", dword(RBP, RDX, 1, CUBES), EBX)
        a.jcc("ne", "OS_ACC_S")
        a.alu("cmp", dword(RBP, RDX, 1, CUBES + 4), R32[13])
        a.jcc("e", "OS_ACC_TROUVE")
        a.etiquette("OS_ACC_S")
        a.alu("add", RCX, 1)
        a.jmp("OS_ACC_CH")
        a.etiquette("OS_ACC_TROUVE")
        a.mov(RDI, qword(RBP, RDX, 1, CUBES + 8))
        # retirer l'entrée (la dernière prend sa place)
        a.mov(RAX, qword(RBP, depl=NCUBES))
        a.alu("sub", RAX, 1)
        a.mov(qword(RBP, depl=NCUBES), RAX)
        a.decaler("shl", RAX, 4)
        a.mov(RSI, qword(RBP, RAX, 1, CUBES))
        a.mov(qword(RBP, RDX, 1, CUBES), RSI)
        a.mov(RSI, qword(RBP, RAX, 1, CUBES + 8))
        a.mov(qword(RBP, RDX, 1, CUBES + 8), RSI)
        a.mov(ESI, ETAGE_OCTETS)
        a.mov(EDX, ETAGE_OCTETS)
        a.mov(R32[10], 3)
        a.mov(R64[8], R64[14])
        appel(25)
        a.test(RAX, RAX)
        a.jcc("s", "E_CUBES")
        a.jmp("OS_ACC_F")
        a.etiquette("OS_ACC_NEUF")
        a.mov(RDI, R64[14])
        a.mov(ESI, ETAGE_OCTETS)
        a.mov(EDX, 3)
        a.mov(R32[10], 0x4032)              # | MAP_FIXED
        a.mov(R64[8], -1)
        a.alu("xor", R32[9], R32[9])
        appel(9)
        a.test(RAX, RAX)
        a.jcc("s", "E_CUBES")
        a.etiquette("OS_ACC_F")
        self.restaurer(TOUS)
        a.ret()

        # OS_DEMARRER : rsp d'origine dans rdi ; arguments : rsi le tableau, edx le nombre (sans le programme)
        a.etiquette("OS_ARGS")
        a.mov(RDX, qword(RDI))
        a.lea(RAX, qword(RDI, RDX, 8, 16))
        a.mov(qword(RBP, depl=ENVP), RAX)
        a.lea(RSI, qword(RDI, depl=16))
        a.alu("sub", EDX, 1)
        a.ret()

    def chaines_os(self):
        a = self.a
        if self.systeme == "windows":
            from socle_windows import chaines_windows
            return chaines_windows(self)
        for nom, t in (("NUL_CHEMIN", b"/dev/null\0"), ("ESPEAK_NG", b"espeak-ng\0"), ("OPT_V", b"-v\0"),
                       ("OPT_FR", b"fr\0"), ("CHEMIN_ESPEAK_NG", b"/usr/bin/espeak-ng\0"),
                       ("CHEMIN_ESPEAK", b"/usr/bin/espeak\0")):
            a.etiquette(nom)
            a.octets(t)

    # ================= le socle commun
    def construire(self, n, corpus):
        """Le socle ; n et corpus ne vont que dans le descripteur."""
        a = self.a
        a.etiquette("DESCRIPTEUR")
        for d, et in (("D_ETAT", "ETAT"), ("D_TABLE", "TABLE"), ("D_PROG", "PROGRAMME")):
            a.etiquette(d)
            a.adresse64(et)
        a.etiquette("D_N")
        a.quad(n)
        a.etiquette("D_P0")
        a.adresse64("P0")
        a.etiquette("D_CORPUS")
        a.quad(1 if corpus else 0)
        a.quad(0)
        a.quad(0)
        a.etiquette("SOCLE")
        self.demarrage()
        self.primitives()
        self.sorties()
        self.canaux()
        self.services()
        self.calculs()
        self.fin()
        self.chaines_os()
        for nom, t in self.messages:
            a.etiquette(nom)
            a.octets(t.encode())
        a.aligner(16)
        a.etiquette("FIN_SOCLE")

    def demarrage(self):
        a = self.a
        a.etiquette("DEMARRER")
        a.mov(RBP, qword(etiq="DESCRIPTEUR"))
        a.mov(RDI, RSP)
        a.alu("and", RSP, -16)
        a.cld()
        a.mov(RAX, qword(etiq="D_CORPUS"))
        a.mov(qword(RBP, depl=CORPUS), RAX)
        a.mov(qword(RBP, depl=FD), 1)
        a.mov(dword(RBP, depl=F2_31), 0x4F000000)
        a.push(RDI)
        a.push(RDI)
        a.call("OS_INIT")
        # mémoire du SPU : 256 Mo réservés
        a.mov(ESI, 4 * ETAGE_OCTETS)
        a.call("OS_RESERVER")
        a.test(RAX, RAX)
        a.jcc("s", "E_MMAP")
        a.mov(R15_, RAX)
        a.mov(ESI, SORTIES_MAX + TEXTE_MAX + ENTREES_MAX)
        a.call("OS_RESERVER")
        a.test(RAX, RAX)
        a.jcc("s", "E_MMAP")
        a.mov(qword(RBP, depl=SBASE), RAX)
        a.alu("add", RAX, SORTIES_MAX)
        a.mov(qword(RBP, depl=TBASE), RAX)
        a.alu("add", RAX, TEXTE_MAX)
        a.mov(qword(RBP, depl=IBASE), RAX)
        # le programme dans l'étage 0
        a.mov(RSI, qword(etiq="D_PROG"))
        a.mov(RDI, R15_)
        a.mov(RCX, qword(etiq="D_N"))
        a.rep_movsd()
        # les entrées : les nombres des arguments (tout ce qui n'est pas un chiffre sépare)
        a.pop(RDI)
        a.pop(RDI)
        a.call("OS_ARGS")                   # rsi : tableau des arguments, edx : leur nombre
        a.mov(R64[12], RSI)
        a.mov(EBX, EDX)
        a.mov(RDI, qword(RBP, depl=IBASE))
        a.alu("xor", R32[13], R32[13])      # nombre d'entrées
        a.etiquette("ARG")
        a.test(EBX, EBX)
        a.jcc("e", "ARG_F")
        a.mov(RSI, qword(R12_))
        a.alu("xor", EAX, EAX)              # valeur
        a.alu("xor", ECX, ECX)              # chiffres vus
        a.etiquette("ARG_C")
        a.movzx8(EDX, byte(RSI))
        a.alu("sub", EDX, 48)
        a.alu("cmp", EDX, 9)
        a.jcc("a", "ARG_SEP")
        a.lea(RAX, qword(RAX, RAX, 4))
        a.alu("add", RAX, RAX)
        a.alu("add", RAX, RDX)
        a.mov(ECX, 1)
        a.jmp("ARG_S")
        a.etiquette("ARG_SEP")
        a.test(ECX, ECX)
        a.jcc("e", "ARG_Z")
        a.mov(dword(RDI, R13_, 4), EAX)
        a.alu("add", R64[13], 1)
        a.alu("xor", EAX, EAX)
        a.alu("xor", ECX, ECX)
        a.etiquette("ARG_Z")
        a.alu("cmp", byte(RSI), 0)
        a.jcc("e", "ARG_N")
        a.etiquette("ARG_S")
        a.alu("add", RSI, 1)
        a.jmp("ARG_C")
        a.etiquette("ARG_N")
        a.alu("add", R64[12], 8)
        a.alu("sub", EBX, 1)
        a.jmp("ARG")
        a.etiquette("ARG_F")
        a.mov(qword(RBP, depl=INB), R64[13])
        # registres du SPU : tous à 0, la pile en haut de l'étage 0
        for r in sorted(CARTE.values()):
            a.alu("xor", R32[r], R32[r])
        a.mov(R32[CARTE[14]], PILE_HAUT)
        a.pxor(XMM[15], XMM[15])
        a.mov(EAX, 1)
        a.movd(XMM[14], RAX)
        a.mov(RAX, qword(etiq="D_P0"))
        a.jmp_r(RAX)

    # --- sorties : tampon, nombres, UTF-8
    def sorties(self):
        a = self.a
        # écrire le tampon de sortie
        a.etiquette("VIDER")
        self.sauver([RCX, RDX, RSI, RDI])
        a.mov(RDI, qword(RBP, depl=FD))
        a.lea(RSI, qword(RBP, depl=OUTBUF))
        a.mov(RDX, qword(RBP, depl=OUTPOS))
        a.call("OS_ECRIRE")
        a.mov(qword(RBP, depl=OUTPOS), 0)
        self.restaurer([RCX, RDX, RSI, RDI])
        a.ret()

        # un octet (al) vers le tampon
        a.etiquette("OCTET")
        a.push(RDX)
        a.mov(RDX, qword(RBP, depl=OUTPOS))
        a.mov(byte(RBP, RDX, 1, OUTBUF), AL)
        a.alu("add", RDX, 1)
        a.mov(qword(RBP, depl=OUTPOS), RDX)
        a.alu("cmp", RDX, TOUT - 64)
        a.pop(RDX)
        a.jcc("b", "OCTET_F")
        a.call("VIDER")
        a.etiquette("OCTET_F")
        a.ret()

        # un nombre (rax, 64 bits non signé) en décimal
        a.etiquette("NOMBRE")
        self.sauver([RAX, RCX, RDX, RSI])
        a.lea(RSI, qword(RBP, depl=CHIFFRES + 32))
        a.mov(ECX, 10)
        a.etiquette("NOMBRE_B")
        a.alu("xor", EDX, EDX)
        a.unaire("div", RCX)
        a.alu("add", EDX, 48)
        a.alu("sub", RSI, 1)
        a.mov(byte(RSI), DL)
        a.test(RAX, RAX)
        a.jcc("ne", "NOMBRE_B")
        a.etiquette("NOMBRE_E")
        a.mov(AL, byte(RSI))
        a.call("OCTET")
        a.alu("add", RSI, 1)
        a.lea(RDX, qword(RBP, depl=CHIFFRES + 32))
        a.alu("cmp", RSI, RDX)
        a.jcc("b", "NOMBRE_E")
        self.restaurer([RAX, RCX, RDX, RSI])
        a.ret()

        # un caractère (eax) en UTF-8 dans [rdi], rdi avancé ; les valeurs qui ne sont pas des caractères sont
        # sautées (comme char::from_u32)
        a.etiquette("UTF8_MEM")
        self.sauver([RAX, RCX, RDX])
        a.alu("and", EAX, 0x1FFFFF)
        a.alu("cmp", EAX, 0x10FFFF)
        a.jcc("a", "UTF8_F")
        a.mov(ECX, EAX)
        a.alu("and", ECX, 0xFFFFF800)
        a.alu("cmp", ECX, 0xD800)
        a.jcc("e", "UTF8_F")
        a.mov(EDX, EAX)
        a.alu("cmp", EDX, 0x80)
        a.jcc("ae", "UTF8_2")
        a.mov(byte(RDI), AL)
        a.alu("add", RDI, 1)
        a.jmp("UTF8_F")

        def suite(decal):
            a.mov(EAX, EDX)
            if decal:
                a.decaler("shr", EAX, decal)
            a.alu("and", EAX, 63)
            a.alu("or", EAX, 0x80)
            a.mov(byte(RDI), AL)
            a.alu("add", RDI, 1)

        a.etiquette("UTF8_2")
        a.alu("cmp", EDX, 0x800)
        a.jcc("ae", "UTF8_3")
        a.decaler("shr", EAX, 6)
        a.alu("or", EAX, 0xC0)
        a.mov(byte(RDI), AL)
        a.alu("add", RDI, 1)
        suite(0)
        a.jmp("UTF8_F")
        a.etiquette("UTF8_3")
        a.alu("cmp", EDX, 0x10000)
        a.jcc("ae", "UTF8_4")
        a.decaler("shr", EAX, 12)
        a.alu("or", EAX, 0xE0)
        a.mov(byte(RDI), AL)
        a.alu("add", RDI, 1)
        suite(6)
        suite(0)
        a.jmp("UTF8_F")
        a.etiquette("UTF8_4")
        a.decaler("shr", EAX, 18)
        a.alu("or", EAX, 0xF0)
        a.mov(byte(RDI), AL)
        a.alu("add", RDI, 1)
        suite(12)
        suite(6)
        suite(0)
        a.etiquette("UTF8_F")
        self.restaurer([RAX, RCX, RDX])
        a.ret()

        # un caractère (eax) en UTF-8 vers le tampon de sortie
        a.etiquette("UTF8")
        self.sauver([RCX, RSI, RDI])
        a.lea(RDI, qword(RBP, depl=CHIFFRES + 64))
        a.call("UTF8_MEM")
        a.lea(RSI, qword(RBP, depl=CHIFFRES + 64))
        a.mov(RCX, RDI)
        a.alu("sub", RCX, RSI)
        a.call("CHAINE")
        self.restaurer([RCX, RSI, RDI])
        a.ret()

        # un texte constant : rsi l'adresse, ecx la longueur
        a.etiquette("CHAINE")
        self.sauver([RAX, RCX, RSI])
        a.etiquette("CHAINE_B")
        a.test(ECX, ECX)
        a.jcc("e", "CHAINE_F")
        a.mov(AL, byte(RSI))
        a.call("OCTET")
        a.alu("add", RSI, 1)
        a.alu("sub", ECX, 1)
        a.jmp("CHAINE_B")
        a.etiquette("CHAINE_F")
        self.restaurer([RAX, RCX, RSI])
        a.ret()

        # IN : l'entrée suivante (0 s'il n'y en a plus)
        a.etiquette("ENTREE")
        a.mov(RDX, qword(RBP, depl=IPOS))
        a.alu("cmp", RDX, qword(RBP, depl=INB))
        a.jcc("ae", "ENTREE_0")
        a.mov(RAX, qword(RBP, depl=IBASE))
        a.mov(EAX, dword(RAX, RDX, 4))
        a.alu("add", RDX, 1)
        a.mov(qword(RBP, depl=IPOS), RDX)
        a.ret()
        a.etiquette("ENTREE_0")
        a.alu("xor", EAX, EAX)
        a.ret()

        # un nombre (eax) vers les sorties / un caractère vers le texte de la console
        for nom, n, b in (("SORTIE", NS, SBASE), ("TEXTE", NT, TBASE)):
            a.etiquette(nom)
            a.mov(RDX, qword(RBP, depl=n))
            a.mov(RCX, qword(RBP, depl=b))
            a.mov(dword(RCX, RDX, 4), EAX)
            a.alu("add", RDX, 1)
            a.mov(qword(RBP, depl=n), RDX)
            a.ret()

    # --- canaux : console (clavier) et fichiers
    def canaux(self):
        a = self.a
        # rdx = l'entrée du canal ecx (2 à 1023) ; ZF = 0 si le canal est ouvert
        a.etiquette("CANAL")
        a.alu("cmp", ECX, NCANAUX)
        a.jcc("ae", "CANAL_NON")
        a.alu("cmp", ECX, 2)
        a.jcc("b", "CANAL_NON")
        a.mov(EDX, ECX)
        a.decaler("shl", EDX, 6)
        a.lea(RDX, qword(RBP, RDX, 1, CANAUX))
        a.alu("cmp", qword(RDX, depl=K_MODE), 0)
        a.ret()
        a.etiquette("CANAL_NON")
        a.alu("xor", EDX, EDX)
        a.test(EDX, EDX)
        a.ret()

        # ENTC : eax le canal -> eax
        a.etiquette("ENTC")
        a.test(EAX, EAX)
        a.jcc("e", "ENTREE")
        a.alu("cmp", EAX, 1)
        a.jcc("e", "ENTC_1")
        a.mov(ECX, EAX)
        a.call("CANAL")
        a.jcc("e", "ENTC_FIN")
        a.alu("cmp", qword(RDX, depl=K_MODE), 1)
        a.jcc("ne", "ENTC_FIN")
        a.mov(RCX, qword(RDX, depl=K_POS))
        a.alu("cmp", RCX, qword(RDX, depl=K_LONG))
        a.jcc("ae", "ENTC_FIN")
        a.mov(RAX, qword(RDX, depl=K_TAMPON))
        a.mov(EAX, dword(RAX, RCX, 4))
        a.alu("add", RCX, 1)
        a.mov(qword(RDX, depl=K_POS), RCX)
        a.ret()
        a.etiquette("ENTC_FIN")
        a.mov(EAX, MASQUE)
        a.ret()
        a.etiquette("ENTC_1")
        a.alu("cmp", qword(RBP, depl=CORPUS), 0)
        a.jcc("ne", "ENTC_FIN")
        # canal 1 : un caractère lu sur l'entrée standard (UTF-8) ; 4294967295 à la fin
        self.sauver(TOUS)
        a.call("LIRE_OCTET")
        a.test(EAX, EAX)
        a.jcc("s", "CLAVIER_FIN")
        a.mov(EBX, EAX)
        a.alu("cmp", EAX, 0x80)
        a.jcc("b", "CLAVIER_OK")
        a.mov(R32[12], 1)
        a.alu("and", EBX, 0x1F)
        a.alu("cmp", EAX, 0xE0)
        a.jcc("b", "CLAVIER_SUITE")
        a.mov(R32[12], 2)
        a.alu("and", EBX, 0x0F)
        a.alu("cmp", EAX, 0xF0)
        a.jcc("b", "CLAVIER_SUITE")
        a.mov(R32[12], 3)
        a.alu("and", EBX, 0x07)
        a.etiquette("CLAVIER_SUITE")
        a.call("LIRE_OCTET")
        a.test(EAX, EAX)
        a.jcc("s", "CLAVIER_FIN")
        a.alu("and", EAX, 63)
        a.decaler("shl", EBX, 6)
        a.alu("or", EBX, EAX)
        a.alu("sub", R32[12], 1)
        a.jcc("ne", "CLAVIER_SUITE")
        a.etiquette("CLAVIER_OK")
        a.mov(EAX, EBX)
        self.restaurer(TOUS)
        a.ret()
        a.etiquette("CLAVIER_FIN")
        a.mov(EAX, MASQUE)
        self.restaurer(TOUS)
        a.ret()
        # un octet de l'entrée standard dans eax, -1 à la fin
        a.etiquette("LIRE_OCTET")
        a.alu("xor", EDI, EDI)
        a.lea(RSI, qword(RBP, depl=OCTET))
        a.mov(EDX, 1)
        a.call("OS_LIRE")
        a.alu("cmp", RAX, 1)
        a.jcc("ne", "LIRE_FIN")
        a.movzx8(EAX, byte(RBP, depl=OCTET))
        a.ret()
        a.etiquette("LIRE_FIN")
        a.mov(EAX, MASQUE)
        a.ret()

        # SORC : eax la valeur, ecx le canal
        a.etiquette("SORC")
        a.test(ECX, ECX)
        a.jcc("e", "SORTIE")
        a.alu("cmp", ECX, 1)
        a.jcc("e", "TEXTE")
        a.push(RAX)
        a.call("CANAL")
        a.pop(RAX)
        a.jcc("e", "SORC_F")
        a.alu("cmp", qword(RDX, depl=K_MODE), 2)
        a.jcc("ne", "SORC_F")
        a.mov(RCX, qword(RDX, depl=K_LONG))
        a.push(RSI)
        a.mov(RSI, qword(RDX, depl=K_TAMPON))
        a.mov(dword(RSI, RCX, 4), EAX)
        a.pop(RSI)
        a.alu("add", RCX, 1)
        a.mov(qword(RDX, depl=K_LONG), RCX)
        a.etiquette("SORC_F")
        a.ret()

        # CHEMIN_DE : eax un texte du SPU (étage << 24 | adresse : longueur puis caractères) -> CHEMIN en UTF-8,
        # terminé par 0 ; rdi : la fin
        a.etiquette("CHEMIN_DE")
        self.sauver([RAX, RCX, RDX, RSI])
        a.mov(EDX, EAX)
        a.decaler("shr", EDX, 24)
        a.alu("and", EDX, 3)
        a.decaler("shl", EDX, 24)
        a.mov(ESI, EAX)
        a.alu("and", ESI, ADR)
        a.lea(EAX, dword(RSI, RDX, 1))
        a.mov(ECX, dword(R15_, RAX, 4))
        a.alu("cmp", ECX, 4096)
        a.jcc("be", "CHEMIN_N")
        a.mov(ECX, 4096)
        a.etiquette("CHEMIN_N")
        a.lea(RDI, qword(RBP, depl=CHEMIN))
        a.etiquette("CHEMIN_B")
        a.test(ECX, ECX)
        a.jcc("e", "CHEMIN_F")
        a.alu("add", ESI, 1)
        a.alu("and", ESI, ADR)
        a.lea(EAX, dword(RSI, RDX, 1))
        a.mov(EAX, dword(R15_, RAX, 4))
        a.call("UTF8_MEM")
        a.alu("sub", ECX, 1)
        a.jmp("CHEMIN_B")
        a.etiquette("CHEMIN_F")
        a.mov(byte(RDI), 0)
        self.restaurer([RAX, RCX, RDX, RSI])
        a.ret()

        # NOUVEAU_CANAL -> ecx le canal (le plus grand ouvert, au moins 1, plus 1), rdx son entrée ; ecx = 0 : plus de place
        a.etiquette("NOUVEAU_CANAL")
        a.mov(ECX, NCANAUX - 1)
        a.etiquette("NC_B")
        a.alu("cmp", ECX, 1)
        a.jcc("be", "NC_T")
        a.mov(EDX, ECX)
        a.decaler("shl", EDX, 6)
        a.alu("cmp", qword(RBP, RDX, 1, CANAUX + K_MODE), 0)
        a.jcc("ne", "NC_T")
        a.alu("sub", ECX, 1)
        a.jmp("NC_B")
        a.etiquette("NC_T")
        a.alu("add", ECX, 1)
        a.alu("cmp", ECX, NCANAUX)
        a.jcc("b", "NC_OK")
        a.alu("xor", ECX, ECX)
        a.ret()
        a.etiquette("NC_OK")
        a.mov(EDX, ECX)
        a.decaler("shl", EDX, 6)
        a.lea(RDX, qword(RBP, RDX, 1, CANAUX))
        a.ret()

        # OUVRIR_L : ecx le nom -> eax le canal (4294967295 : échec)
        a.etiquette("OUVRIR_L")
        self.sauver(TOUS)
        a.alu("cmp", qword(RBP, depl=CORPUS), 0)
        a.jcc("ne", "OUV_ECHEC")
        a.mov(EAX, ECX)
        a.call("CHEMIN_DE")
        a.lea(RDI, qword(RBP, depl=CHEMIN))
        a.alu("xor", ESI, ESI)
        a.call("OS_OUVRIR")
        a.test(RAX, RAX)
        a.jcc("s", "OUV_ECHEC")
        a.mov(RBX, RAX)                     # descripteur
        a.mov(RDI, RAX)
        a.call("OS_TAILLE")
        a.test(RAX, RAX)
        a.jcc("s", "OUV_FERMER")
        a.mov(R64[12], RAX)                 # taille en octets
        # région : nom, caractères (4 octets chacun), octets lus
        a.lea(RSI, qword(RAX, RAX, 4, TCHEMIN + 4096))
        a.mov(R64[14], RSI)
        a.call("OS_RESERVER")
        a.test(RAX, RAX)
        a.jcc("s", "OUV_FERMER")
        a.mov(R64[13], RAX)
        # lire tout le fichier
        a.lea(RSI, qword(RAX, R12_, 4, TCHEMIN + 64))
        a.mov(R64[8], RSI)                  # début des octets
        a.mov(R64[9], R64[12])              # reste à lire
        a.etiquette("OUV_LIRE")
        a.test(R64[9], R64[9])
        a.jcc("e", "OUV_LU")
        a.mov(RDI, RBX)
        a.mov(RDX, R64[9])
        a.call("OS_LIRE")
        a.test(RAX, RAX)
        a.jcc("le", "OUV_LU")
        a.alu("add", RSI, RAX)
        a.alu("sub", R64[9], RAX)
        a.jmp("OUV_LIRE")
        a.etiquette("OUV_LU")
        a.mov(R64[9], RSI)                  # fin des octets
        a.mov(RDI, RBX)
        a.call("OS_FERMER")
        # décoder (UTF-8 strict, comme read_to_string)
        a.lea(RDI, qword(R13_, depl=TCHEMIN))
        a.mov(RSI, R64[8])
        a.call("DECODER")
        a.test(RAX, RAX)
        a.jcc("s", "OUV_RENDRE")
        a.mov(R64[10], RAX)                 # nombre de caractères
        a.call("NOUVEAU_CANAL")
        a.test(ECX, ECX)
        a.jcc("e", "OUV_RENDRE")
        a.mov(qword(RDX, depl=K_MODE), 1)
        a.lea(RAX, qword(R13_, depl=TCHEMIN))
        a.mov(qword(RDX, depl=K_TAMPON), RAX)
        a.mov(qword(RDX, depl=K_LONG), R64[10])
        a.mov(qword(RDX, depl=K_POS), 0)
        a.mov(qword(RDX, depl=K_REGION), R64[13])
        a.mov(qword(RDX, depl=K_TAILLE), R64[14])
        a.mov(qword(RDX, depl=K_NOM), R64[13])
        a.mov(EAX, ECX)
        self.copier_chemin(R64[13])
        self.restaurer(TOUS)
        a.ret()
        a.etiquette("OUV_RENDRE")
        a.mov(RDI, R64[13])
        a.mov(RSI, R64[14])
        a.call("OS_RENDRE")
        a.jmp("OUV_ECHEC")
        a.etiquette("OUV_FERMER")
        a.mov(RDI, RBX)
        a.call("OS_FERMER")
        a.etiquette("OUV_ECHEC")
        a.mov(EAX, MASQUE)
        self.restaurer(TOUS)
        a.ret()

        # DECODER : octets de rsi à r9 (exclu) -> caractères en [rdi] ; rax leur nombre, -1 si l'UTF-8 est invalide
        a.etiquette("DECODER")
        self.sauver([RBX, RCX, RDX, RSI, RDI, R8_])
        a.mov(R64[8], RDI)
        a.etiquette("DEC_B")
        a.alu("cmp", RSI, R64[9])
        a.jcc("ae", "DEC_F")
        a.movzx8(EAX, byte(RSI))
        a.alu("add", RSI, 1)
        a.alu("cmp", EAX, 0x80)
        a.jcc("b", "DEC_MET")
        a.alu("cmp", EAX, 0xC2)
        a.jcc("b", "DEC_ERR")
        a.mov(ECX, 1)
        a.mov(EBX, 0x80)                    # plus petite valeur permise
        a.alu("and", EAX, 0x1F)
        a.alu("cmp", byte(RSI, depl=-1), 0xE0)
        a.jcc("b", "DEC_S")
        a.movzx8(EAX, byte(RSI, depl=-1))
        a.mov(ECX, 2)
        a.mov(EBX, 0x800)
        a.alu("and", EAX, 0x0F)
        a.alu("cmp", byte(RSI, depl=-1), 0xF0)
        a.jcc("b", "DEC_S")
        a.movzx8(EAX, byte(RSI, depl=-1))
        a.alu("cmp", EAX, 0xF5)
        a.jcc("ae", "DEC_ERR")
        a.mov(ECX, 3)
        a.mov(EBX, 0x10000)
        a.alu("and", EAX, 0x07)
        a.etiquette("DEC_S")
        a.alu("cmp", RSI, R64[9])
        a.jcc("ae", "DEC_ERR")
        a.movzx8(EDX, byte(RSI))
        a.alu("add", RSI, 1)
        a.push(RDX)
        a.alu("and", EDX, 0xC0)
        a.alu("cmp", EDX, 0x80)
        a.pop(RDX)
        a.jcc("ne", "DEC_ERR")
        a.alu("and", EDX, 63)
        a.decaler("shl", EAX, 6)
        a.alu("or", EAX, EDX)
        a.alu("sub", ECX, 1)
        a.jcc("ne", "DEC_S")
        a.alu("cmp", EAX, EBX)
        a.jcc("b", "DEC_ERR")
        a.alu("cmp", EAX, 0x10FFFF)
        a.jcc("a", "DEC_ERR")
        a.mov(EDX, EAX)
        a.alu("and", EDX, 0xFFFFF800)
        a.alu("cmp", EDX, 0xD800)
        a.jcc("e", "DEC_ERR")
        a.etiquette("DEC_MET")
        a.mov(dword(RDI), EAX)
        a.alu("add", RDI, 4)
        a.jmp("DEC_B")
        a.etiquette("DEC_F")
        a.mov(RAX, RDI)
        a.alu("sub", RAX, R64[8])
        a.decaler("shr", RAX, 2)
        self.restaurer([RBX, RCX, RDX, RSI, RDI, R8_])
        a.ret()
        a.etiquette("DEC_ERR")
        a.mov(RAX, -1)
        self.restaurer([RBX, RCX, RDX, RSI, RDI, R8_])
        a.ret()

        # OUVRIR_E : ecx le nom -> eax le canal (le fichier est écrit à la fermeture)
        a.etiquette("OUVRIR_E")
        self.sauver(TOUS)
        a.alu("cmp", qword(RBP, depl=CORPUS), 0)
        a.jcc("ne", "OUV_ECHEC")
        a.mov(EAX, ECX)
        a.call("CHEMIN_DE")
        a.mov(ESI, ECRITURE_MAX)
        a.call("OS_RESERVER")
        a.test(RAX, RAX)
        a.jcc("s", "OUV_ECHEC")
        a.mov(R64[13], RAX)
        a.call("NOUVEAU_CANAL")
        a.test(ECX, ECX)
        a.jcc("e", "OUVE_RENDRE")
        a.mov(qword(RDX, depl=K_MODE), 2)
        a.lea(RAX, qword(R13_, depl=TCHEMIN))
        a.mov(qword(RDX, depl=K_TAMPON), RAX)
        a.mov(qword(RDX, depl=K_LONG), 0)
        a.mov(qword(RDX, depl=K_POS), 0)
        a.mov(qword(RDX, depl=K_REGION), R64[13])
        a.mov(EAX, ECRITURE_MAX)
        a.mov(qword(RDX, depl=K_TAILLE), RAX)
        a.mov(qword(RDX, depl=K_NOM), R64[13])
        a.mov(EAX, ECX)
        self.copier_chemin(R64[13])
        self.restaurer(TOUS)
        a.ret()
        a.etiquette("OUVE_RENDRE")
        a.mov(RDI, R64[13])
        a.mov(ESI, ECRITURE_MAX)
        a.call("OS_RENDRE")
        a.jmp("OUV_ECHEC")

        # FERMER : ecx le canal -> eax (0, ou 4294967295 si le canal n'est pas ouvert)
        a.etiquette("FERMER")
        self.sauver(TOUS)
        a.call("CANAL")
        a.jcc("e", "OUV_ECHEC")
        a.mov(RBX, RDX)
        a.alu("cmp", qword(RBX, depl=K_MODE), 2)
        a.jcc("ne", "FER_RENDRE")
        # le texte en UTF-8, dans la région, après les caractères
        a.mov(RSI, qword(RBX, depl=K_TAMPON))
        a.mov(RCX, qword(RBX, depl=K_LONG))
        a.lea(RDI, qword(RSI, RCX, 4, 64))
        a.mov(R64[12], RDI)                 # début du texte
        a.etiquette("FER_ENC")
        a.test(RCX, RCX)
        a.jcc("e", "FER_ENC_F")
        a.mov(EAX, dword(RSI))
        a.call("UTF8_MEM")
        a.alu("add", RSI, 4)
        a.alu("sub", RCX, 1)
        a.jmp("FER_ENC")
        a.etiquette("FER_ENC_F")
        a.mov(byte(RDI), 0)
        a.mov(R64[13], RDI)                 # fin du texte
        # le canal « voix: » : le texte est dit par la machine
        a.mov(RDI, qword(RBX, depl=K_NOM))
        a.call("EST_VOIX")
        a.jcc("ne", "FER_FICHIER")
        a.mov(RSI, R64[12])
        a.call("PARLER")
        a.jmp("FER_RENDRE")
        a.etiquette("FER_FICHIER")
        a.mov(RDI, qword(RBX, depl=K_NOM))
        a.mov(ESI, 1)
        a.call("OS_OUVRIR")
        a.test(RAX, RAX)
        a.jcc("s", "FER_RENDRE")
        a.mov(R64[14], RAX)
        a.mov(RDI, RAX)
        a.mov(RSI, R64[12])
        a.mov(RDX, R64[13])
        a.alu("sub", RDX, RSI)
        a.call("OS_ECRIRE")
        a.mov(RDI, R64[14])
        a.call("OS_FERMER")
        a.etiquette("FER_RENDRE")
        a.mov(RDI, qword(RBX, depl=K_REGION))
        a.mov(RSI, qword(RBX, depl=K_TAILLE))
        a.call("OS_RENDRE")
        a.mov(qword(RBX, depl=K_MODE), 0)
        a.alu("xor", EAX, EAX)
        self.restaurer(TOUS)
        a.ret()

        # EST_VOIX : rdi un nom terminé par 0 ; ZF = 1 si son dernier élément est « voix: »
        a.etiquette("EST_VOIX")
        self.sauver([RAX, RCX, RSI, RDI])
        a.mov(RSI, RDI)                     # début du dernier élément
        a.etiquette("EV_B")
        a.mov(AL, byte(RDI))
        a.test(AL, AL)
