    def copier_chemin(self, dest):
        """Recopie CHEMIN (TCHEMIN octets) au début de la région dest."""
        a = self.a
        a.push(RCX)
        a.lea(RSI, qword(RBP, depl=CHEMIN))
        a.mov(RDI, dest)
        a.mov(ECX, TCHEMIN)
        a.rep_movsb()
        a.pop(RCX)

    # --- services (SYS)
    def services(self):
        a = self.a
        # SYS : eax le service, ecx l'argument -> eax
        a.etiquette("SYS")
        for n, et in ((1, "OUVRIR_L"), (2, "OUVRIR_E"), (3, "FERMER"), (4, "FINI"), (5, "OS_BRUIT"), (6, "BLOC"),
                      (7, "BLOC"), (8, "ACCORDER"), (9, "FREQUENCE"), (10, "E_PLEINE")):
            a.alu("cmp", EAX, n)
            a.jcc("e", et)
        a.mov(EAX, MASQUE)
        a.ret()
        a.etiquette("FREQUENCE")
        a.alu("and", ECX, 3)
        a.mov(EAX, dword(RBP, RCX, 4, FREQ))
        a.ret()
        # ACCORDER : argument = fréquence × 4 + étage ; rend l'ancienne fréquence (4294967295 pour l'étage 0)
        a.etiquette("ACCORDER")
        a.mov(EDX, ECX)
        a.decaler("shr", EDX, 2)
        a.alu("and", ECX, 3)
        a.jcc("e", "ACC_0")
        a.mov(EAX, dword(RBP, RCX, 4, FREQ))
        a.alu("cmp", EAX, EDX)
        a.jcc("e", "ACC_F")
        a.push(RAX)
        a.call("OS_ACCORDER")
        a.pop(RAX)
        a.mov(dword(RBP, RCX, 4, FREQ), EDX)
        a.etiquette("ACC_F")
        a.ret()
        a.etiquette("ACC_0")
        a.mov(EAX, MASQUE)
        a.ret()

    # --- calculs longs : GDOT, GEMV, MIN/MAX quit par quit
    def calculs(self):
        a = self.a
        # GDOT : eax, ecx -> eax (somme des produits octet par octet)
        a.etiquette("GDOT")
        self.sauver([RCX, RDX, RSI, RDI])
        a.mov(ESI, EAX)
        a.mov(EDI, ECX)
        a.alu("xor", ECX, ECX)
        for _ in range(4):
            a.mov(EAX, ESI)
            a.alu("and", EAX, 255)
            a.mov(EDX, EDI)
            a.alu("and", EDX, 255)
            a.imul(EAX, EDX)
            a.alu("add", ECX, EAX)
            a.decaler("shr", ESI, 8)
            a.decaler("shr", EDI, 8)
        a.mov(EAX, ECX)
        self.restaurer([RCX, RDX, RSI, RDI])
        a.ret()

        # GEMV : arguments sur la pile du SPU (edx = R14) : n, w, q, k, o ; étage 2
        a.etiquette("GEMV")
        self.sauver(TOUS)
        for reg, t in ((8, 0), (9, 1), (10, 2), (11, 3), (12, 4)):    # n, w, q, k, o
            a.lea(EAX, dword(RDX, depl=4 - t))
            a.alu("and", EAX, ADR)
            a.mov(R32[reg], dword(R15_, RAX, 4))
        a.alu("xor", R32[13], R32[13])       # i
        a.etiquette("GEMV_I")
        a.alu("cmp", R32[13], R32[8])
        a.jcc("ae", "GEMV_F")
        a.alu("xor", EBX, EBX)               # somme (seul le mot bas est gardé)
        a.mov(R32[14], R32[11])
        a.mov(EAX, R32[13])
        a.imul(EAX, R32[9])
        a.alu("add", R32[14], EAX)           # k + i*w
        a.alu("xor", ESI, ESI)               # j
        a.etiquette("GEMV_J")
        a.alu("cmp", ESI, R32[9])
        a.jcc("ae", "GEMV_FJ")
        a.lea(EAX, dword(R10_, RSI, 1))
        a.alu("and", EAX, ADR)
        a.mov(EAX, dword(R15_, RAX, 4, 2 << 26))
        a.lea(ECX, dword(R14_, RSI, 1))
        a.alu("and", ECX, ADR)
        a.mov(ECX, dword(R15_, RCX, 4, 2 << 26))
        a.call("GDOT")
        a.alu("add", EBX, EAX)
        a.alu("add", ESI, 1)
        a.jmp("GEMV_J")
        a.etiquette("GEMV_FJ")
        a.lea(EAX, dword(R12_, R13_, 1))
        a.alu("and", EAX, ADR)
        a.mov(dword(R15_, RAX, 4, 2 << 26), EBX)
        a.alu("add", R32[13], 1)
        a.jmp("GEMV_I")
        a.etiquette("GEMV_F")
        self.restaurer(TOUS)
        a.ret()

        # QUITS : MIN / MAX quit par quit : eax, ecx ; edx = 0 (min) ou 1 (max) -> eax
        a.etiquette("QUITS")
        self.sauver([RSI, RDI, R8_])
        a.mov(R32[8], EDX)
        a.mov(ESI, EAX)                       # x
        a.mov(EDI, ECX)                       # y
        a.mov(EAX, ESI)
        a.unaire("not", EAX)
        a.alu("and", EAX, EDI)                # d = ~x & y
        a.mov(EDX, ESI)
        a.alu("xor", EDX, EDI)
        a.unaire("not", EDX)                  # e = ~(x ^ y)
        a.mov(ECX, EAX)
        a.alu("and", ECX, 0x55555555)
        a.alu("add", ECX, ECX)
        a.alu("and", ECX, EDX)
        a.alu("or", ECX, EAX)
        a.alu("and", ECX, 0xAAAAAAAA)         # x < y, dans le bit haut de chaque quit
        a.mov(EAX, ECX)
        a.decaler("shr", EAX, 1)
        a.alu("or", ECX, EAX)                 # 11 là où x < y
        a.test(R32[8], R32[8])
        a.jcc("ne", "QUITS_MAX")
        a.mov(EAX, ESI)
        a.alu("and", EAX, ECX)
        a.unaire("not", ECX)
        a.alu("and", ECX, EDI)
        a.alu("or", EAX, ECX)
        a.jmp("QUITS_F")
        a.etiquette("QUITS_MAX")
        a.mov(EAX, EDI)
        a.alu("and", EAX, ECX)
        a.unaire("not", ECX)
        a.alu("and", ECX, ESI)
        a.alu("or", EAX, ECX)
        a.etiquette("QUITS_F")
        self.restaurer([RSI, RDI, R8_])
        a.ret()

    # --- fin et erreurs
    def fin(self):
        a = self.a
        # erreurs du programme : message (rsi, ecx)
        a.etiquette("ERREUR")
        a.mov(qword(RBP, depl=OUTPOS), 0)
        a.alu("cmp", qword(RBP, depl=CORPUS), 0)
        a.jcc("ne", "ERREUR_C")
        a.push(RSI)
        a.push(RCX)
        self.msg("erreur : ")
        a.call("CHAINE")
        a.mov(qword(RBP, depl=FD), 2)
        a.jmp("ERREUR_M")
        a.etiquette("ERREUR_C")
        a.push(RSI)
        a.push(RCX)
        self.msg("ERREUR ")
        a.call("CHAINE")
        a.etiquette("ERREUR_M")
        a.pop(RCX)
        a.pop(RSI)
        a.call("CHAINE")
        a.mov(AL, 10)
        a.call("OCTET")
        a.call("VIDER")
        a.alu("xor", EDI, EDI)
        a.alu("cmp", qword(RBP, depl=CORPUS), 0)
        a.jcc("ne", "ERREUR_Q")
        a.mov(EDI, 1)
        a.etiquette("ERREUR_Q")
        a.jmp("OS_QUITTER")

        for nom, m in (("E_RETOUR", "retour à une adresse qui n'est pas une instruction"),
                       ("E_HORS", "le programme est sorti de son code"),
                       ("E_DMA", "DMA non implémentée (utiliser copier du prélude)"),
                       ("E_MMAP", "mémoire : réservation impossible"),
                       ("E_CUBES", "accorder : trop de cubes rangés, ou mémoire refusée"),
                       ("E_PLEINE", "mémoire pleine : le tas ne peut plus grandir, même après avoir ramassé les miettes")):
            a.etiquette(nom)
            self.msg(m)
            a.jmp("ERREUR")

        # E_INCONNU : eax l'adresse, ecx le code d'opération
        a.etiquette("E_INCONNU")
        a.mov(EBX, EAX)
        a.mov(R32[12], ECX)
        a.mov(qword(RBP, depl=OUTPOS), 0)
        self.msg("code d'opération inconnu : 0x")
        a.call("CHAINE")
        for decal in (4, 0):
            a.mov(EAX, R32[12])
            a.decaler("shr", EAX, decal)
            a.alu("and", EAX, 15)
            a.lea(RCX, qword(etiq="HEX"))
            a.mov(AL, byte(RCX, RAX, 1))
            a.call("OCTET")
        self.msg(" à l'adresse ")
        a.call("CHAINE")
        a.mov(EAX, EBX)
        a.call("NOMBRE")
        a.lea(RSI, qword(RBP, depl=OUTBUF))
        a.mov(RCX, qword(RBP, depl=OUTPOS))
        a.lea(RDI, qword(RBP, depl=CHIFFRES + 128))
        a.push(RCX)
        a.rep_movsb()
        a.pop(RCX)
        a.lea(RSI, qword(RBP, depl=CHIFFRES + 128))
        a.jmp("ERREUR")
        a.etiquette("HEX")
        a.octets(b"0123456789abcdef")

        # FIN (HALT)
        a.etiquette("FIN")
        a.alu("cmp", qword(RBP, depl=CORPUS), 0)
        a.jcc("ne", "FIN_CORPUS")
        self.liste("SORTIES_L", NS, SBASE, nombres=True)
        a.mov(RAX, qword(RBP, depl=NS))
        a.test(RAX, RAX)
        a.jcc("e", "FIN_T")
        a.mov(AL, 10)
        a.call("OCTET")
        a.etiquette("FIN_T")
        self.liste("TEXTE_L", NT, TBASE, nombres=False)
        a.jmp("FIN_Q")
        # corpus : « instructions|sorties|mémoire[|T:texte] »
        a.etiquette("FIN_CORPUS")
        a.movd(RAX, XMM[15])
        a.call("NOMBRE")
        a.mov(AL, ord("|"))
        a.call("OCTET")
        self.liste("SORTIES_C", NS, SBASE, nombres=True)
        a.mov(AL, ord("|"))
        a.call("OCTET")
        self.etat_memoire()
        a.mov(RAX, qword(RBP, depl=NT))
        a.test(RAX, RAX)
        a.jcc("e", "FIN_N")
        self.msg("|T:")
        a.call("CHAINE")
        self.liste("TEXTE_C", NT, TBASE, nombres=True)
        a.etiquette("FIN_N")
        a.mov(AL, 10)
        a.call("OCTET")
        a.etiquette("FIN_Q")
        a.call("VIDER")
        a.alu("xor", EDI, EDI)
        a.jmp("OS_QUITTER")

    def liste(self, nom, n, b, nombres):
        """Écrit la liste (sorties ou texte) : nombres séparés par des virgules, ou caractères en UTF-8."""
        a = self.a
        a.alu("xor", EBX, EBX)
        a.etiquette(nom)
        a.alu("cmp", RBX, qword(RBP, depl=n))
        a.jcc("ae", nom + "_F")
        if nombres:
            a.test(RBX, RBX)
            a.jcc("e", nom + "_V")
            a.mov(AL, ord(","))
            a.call("OCTET")
            a.etiquette(nom + "_V")
        a.mov(RCX, qword(RBP, depl=b))
        a.mov(EAX, dword(RCX, RBX, 4))
        a.call("NOMBRE" if nombres else "UTF8")
        a.alu("add", RBX, 1)
        a.jmp(nom)
        a.etiquette(nom + "_F")

    def etat_memoire(self):
        """Les mots non nuls des étages 1 à 3 : « adresse:valeur » séparés par des virgules (pages présentes seulement)."""
        a = self.a
        a.call("OS_PAGES")
        a.mov(qword(RBP, depl=PREMIER), 1)
        a.alu("xor", EBX, EBX)               # page
        a.etiquette("MEM_P")
        a.alu("cmp", EBX, 3 << 14)
        a.jcc("ae", "MEM_F")
        a.movzx8(EAX, byte(RBP, RBX, 1, VEC))
        a.test(EAX, 1)
        a.jcc("e", "MEM_S")
        a.mov(R32[12], EBX)
        a.decaler("shl", R32[12], 10)
        a.alu("add", R32[12], 1 << 24)       # index du premier mot de la page
        a.alu("xor", R32[13], R32[13])
        a.etiquette("MEM_M")
        a.lea(EAX, dword(R12_, R13_, 1))
        a.mov(ECX, dword(R15_, RAX, 4))
        a.test(ECX, ECX)
        a.jcc("e", "MEM_N")
        a.alu("cmp", qword(RBP, depl=PREMIER), 0)
        a.mov(qword(RBP, depl=PREMIER), 0)
        a.jcc("ne", "MEM_V")
        a.push(RAX)
        a.mov(AL, ord(","))
        a.call("OCTET")
        a.pop(RAX)
        a.etiquette("MEM_V")
        a.call("NOMBRE")
        a.mov(AL, ord(":"))
        a.call("OCTET")
        a.mov(EAX, ECX)
        a.call("NOMBRE")
        a.etiquette("MEM_N")
        a.alu("add", R32[13], 1)
        a.alu("cmp", R32[13], 1024)
        a.jcc("b", "MEM_M")
        a.etiquette("MEM_S")
        a.alu("add", EBX, 1)
        a.jmp("MEM_P")
        a.etiquette("MEM_F")
