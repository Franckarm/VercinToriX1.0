        a.lea(EAX, dword(R14_, RCX, 1))
        a.alu("and", EAX, ADR)
        a.alu("or", EAX, R32[12])
        a.mov(EAX, dword(R15_, RAX, 4))
        a.mov(dword(R8_, RCX, 4), EAX)
        a.alu("add", ECX, 1)
        a.jmp("BLOC_E")
        a.etiquette("BLOC_EF")
        a.lea(RDI, qword(RBP, depl=CHEMIN))
        a.mov(ESI, 1)
